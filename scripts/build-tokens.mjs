#!/usr/bin/env node
/**
 * Generates Tailwind CSS v4 theme tokens from the design-system exports in design/tokens/.
 *
 * Each system gets its own prefix so both variants can live in one codebase:
 *   ag-* → Apple-inspired (variant A · Afterglow)
 *   bo-* → Nike-inspired  (variant B · Blackout)
 *
 * Output: src/styles/tokens.generated.css (git-ignored, rebuilt before dev/build).
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIR = path.join(ROOT, 'design/tokens');
const OUTPUT = path.join(ROOT, 'src/styles/tokens.generated.css');

/** Web fallbacks the systems name, mapped to the next/font CSS variables set in app/layout.tsx. */
const FONT_VARIABLES = {
  'Inter Tight': 'var(--font-inter-tight)',
  Inter: 'var(--font-inter)',
  Oswald: 'var(--font-oswald)',
};

const SYSTEMS = [
  {
    file: 'apple-inspired.tokens.json',
    prefix: 'ag',
    // The system asks for +0.02–0.06 line height on text styles when Inter stands in for SF Pro Text.
    lineHeightBump: { text: 0.04 },
  },
  { file: 'nike-inspired.tokens.json', prefix: 'bo', lineHeightBump: {} },
];

const kebab = (value) =>
  String(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const round = (value) => Math.round(value * 1000) / 1000;

function resolveReference(value, palette, trail = []) {
  const match = typeof value === 'string' ? value.match(/^\{(.+)\}$/) : null;
  if (!match) return value;
  const name = match[1];
  if (trail.includes(name)) throw new Error(`Circular token reference: ${[...trail, name].join(' → ')}`);
  const target = palette.get(name);
  if (target === undefined) throw new Error(`Unknown token reference: {${name}}`);
  if (typeof target !== 'string')
    throw new Error(`Token {${name}} is themed and cannot be referenced directly`);
  return resolveReference(target, palette, [...trail, name]);
}

function colorTokens(system, prefix) {
  const palette = new Map(system.color.tokens.map((token) => [token.name, token.value]));
  return system.color.tokens.flatMap((token) => {
    const name = `--color-${prefix}-${kebab(token.name)}`;
    if (typeof token.value === 'string') return [`${name}: ${resolveReference(token.value, palette)};`];
    return Object.entries(token.value).map(
      ([theme, value]) => `${name}-${kebab(theme)}: ${resolveReference(value, palette)};`,
    );
  });
}

function textTokens(system, prefix, lineHeightBump) {
  return system.type.groups.flatMap((group) =>
    group.styles.flatMap((style) => {
      const name = `--text-${prefix}-${kebab(style.name)}`;
      const lines = [
        `${name}: ${style.fontSize};`,
        `${name}--line-height: ${round(style.lineHeight + (lineHeightBump[group.family] ?? 0))};`,
      ];
      if (style.letterSpacing && style.letterSpacing !== '0px') {
        lines.push(`${name}--letter-spacing: ${style.letterSpacing};`);
      }
      if (style.fontWeight) lines.push(`${name}--font-weight: ${style.fontWeight};`);
      return lines;
    }),
  );
}

function fontTokens(system, prefix) {
  return Object.entries(system.type.families).map(([family, stack]) => {
    const resolved = stack
      .split(',')
      .map((entry) => entry.trim())
      .map((entry) => FONT_VARIABLES[entry.replace(/^["']|["']$/g, '')] ?? entry)
      .join(', ');
    return `--font-${prefix}-${kebab(family)}: ${resolved};`;
  });
}

function prefixedTokens(group, namespace, prefix, stripPrefix) {
  return (group?.tokens ?? []).map(
    (token) => `--${namespace}-${prefix}-${kebab(token.name.replace(stripPrefix, ''))}: ${token.value};`,
  );
}

async function main() {
  const staticBlock = [];
  const inlineBlock = [];

  for (const { file, prefix, lineHeightBump } of SYSTEMS) {
    const system = JSON.parse(await readFile(path.join(SOURCE_DIR, file), 'utf8'));
    staticBlock.push(
      `  /* ${system.name} → ${prefix}-* */`,
      ...colorTokens(system, prefix),
      ...textTokens(system, prefix, lineHeightBump),
      ...prefixedTokens(system.radius, 'radius', prefix, /^radius-/),
      ...prefixedTokens(system.shadow, 'shadow', prefix, /^shadow-/),
    );
    inlineBlock.push(...fontTokens(system, prefix));
  }

  const indent = (lines) => lines.map((line) => (line.startsWith('  ') ? line : `  ${line}`)).join('\n');
  const css = [
    '/* Generated by scripts/build-tokens.mjs from design/tokens/*.tokens.json — do not edit by hand. */',
    '',
    '@theme {',
    indent(staticBlock),
    '}',
    '',
    '/* Font stacks reference next/font variables, so they must stay inline. */',
    '@theme inline {',
    indent(inlineBlock),
    '}',
    '',
  ].join('\n');

  await mkdir(path.dirname(OUTPUT), { recursive: true });
  await writeFile(OUTPUT, css, 'utf8');
  console.log(
    `tokens: wrote ${path.relative(ROOT, OUTPUT)} (${staticBlock.length + inlineBlock.length} lines)`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
